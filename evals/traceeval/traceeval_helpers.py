def format_test_input(input_data: dict[str, Any]) -> str:
    """Format input data as a human-readable string for test output.

    Args:
        input_data: Dictionary of test input parameters.

    Returns:
        Formatted string representation.
    """
    parts = []
    for key, value in input_data.items():
        parts.append(f"  {key}: {value}")
    return "\n".join(parts) if parts else "(empty input)"
