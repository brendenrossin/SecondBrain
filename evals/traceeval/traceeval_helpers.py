def assert_contains(text: str, expected: str, msg: str = "") -> None:
    """Assert that `expected` is a substring of `text`.

    Args:
        text: The text to search within.
        expected: The substring to look for.
        msg: Optional message on failure.
    """
    if expected not in text:
        detail = f"Expected '{expected}' to be found in text"
        if msg:
            detail = f"{msg}: {detail}"
        raise AssertionError(detail)


